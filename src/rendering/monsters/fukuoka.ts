/** 光の すじ（まん中から のびる とげとげ。C＝光、G＝先っぽ）。岩手の 後光と 同じ 作り方 */
function glow(size: number, cy: number, rIn: number, rOut: number, n: number, bottom: number): string[] {
  const cx = (size - 1) / 2;
  return Array.from({ length: size }, (_, y) =>
    Array.from({ length: size }, (_, x) => {
      const d = Math.hypot(x - cx, y - cy);
      const a = Math.abs(Math.atan2(x - cx, cy - y));
      const u = (a / ((2 * Math.PI) / n)) % 1;
      const r = rIn + (rOut - rIn) * (1 - 2 * Math.min(u, 1 - u));
      if (d > r || y > bottom || x < 1 || y < 1 || x > size - 2) return '.';
      return d > r - 2.5 ? 'G' : 'C';
    }).join(''),
  );
}

